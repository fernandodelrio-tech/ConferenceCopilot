#!/usr/bin/env node
// Builds dist/ascendant.html — one self-contained file that runs by double-clicking,
// with no server, no install and no network.
//
// Why a build step is needed at all: the served version uses ES modules and fetch,
// and browsers block both on the file:// origin. So this inlines everything —
// modules, content JSON, and every baked PNG as a data URI.
//
// Data URIs specifically, not file:// image paths. A file:// image taints the canvas
// it is drawn into, and the bloom pass draws a canvas into another canvas; data URIs
// are same-origin and never taint.
//
// The module transform is deliberately simple: strip import/export syntax and
// concatenate in dependency order inside one scope. That is only safe if every
// top-level name across the bundle is unique, so the bundler CHECKS that and refuses
// to emit if it is not, rather than producing a file that silently misbehaves.

import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';

// Dependency order. sim/profile.js is authoring-time only and is not bundled.
const MODULES = [
  'sim/rng.js',
  'sim/trig.js',
  'sim/lane.js',
  'sim/rules.js',
  'sim/sim.js',
  'render/fit.js',
  'render/assets.js',
  'render/vfx.js',
  'render/post.js',
  'render/staticlayer.js',
  'render/draw.js',
  'platform/content.js',
  'platform/input.js',
  'platform/audio.js',
  'platform/storage.js',
  'platform/shell.js',
];

const CONTENT = [
  'content/tuning.json',
  'content/trig.json',
  'content/lanes/index.json',
  ...Array.from({ length: 12 }, (_, i) => `content/lanes/${String(i + 1).padStart(2, '0')}.json`),
];

const IMPORT_RE = /import\s+(?:[\w*\s{},$]+)\s+from\s+['"][^'"]+['"];?/g;
const NAMESPACE_IMPORT_RE = /import\s+\*\s+as\s+([\w$]+)\s+from\s+['"]\.\/([\w./-]+)['"];?/g;
const DECL_RE = /^(?:export\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm;

const exportsByModule = new Map();
const declaredIn = new Map();
const chunks = [];
let collisions = [];

for (const path of MODULES) {
  const raw = readFileSync(path, 'utf8');

  // Record this module's exported names so `import * as ns` can be reconstructed.
  const exported = [];
  for (const m of raw.matchAll(/^export\s+(?:async\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    exported.push(m[1]);
  }
  exportsByModule.set(path.split('/').pop(), exported);

  // Every top-level declaration, for the uniqueness check.
  for (const m of raw.matchAll(DECL_RE)) {
    const name = m[1];
    if (declaredIn.has(name)) collisions.push(`${name} (${declaredIn.get(name)} and ${path})`);
    else declaredIn.set(name, path);
  }

  let src = raw;

  // `import * as storage from './storage.js'` -> a plain object of that module's exports.
  src = src.replace(NAMESPACE_IMPORT_RE, (_all, ns, file) => {
    const names = exportsByModule.get(file.split('/').pop()) || [];
    return `const ${ns} = { ${names.join(', ')} };`;
  });

  src = src.replace(IMPORT_RE, '');
  src = src.replace(/^export\s+(?=(?:async\s+)?(?:const|let|var|function|class)\s)/gm, '');
  src = src.replace(/^export\s*\{[^}]*\};?\s*$/gm, '');

  chunks.push(`// ---------------------------------------------------------------- ${path}\n${src.trim()}\n`);
}

if (collisions.length) {
  console.error('bundle aborted — duplicate top-level names across modules:');
  for (const c of new Set(collisions)) console.error(`  ${c}`);
  process.exit(1);
}

// ------------------------------------------------------------------ inline data

const content = {};
for (const p of CONTENT) content[p] = JSON.parse(readFileSync(p, 'utf8'));

const manifest = JSON.parse(readFileSync('assets/manifest.json', 'utf8'));
const images = {};
for (const [name, meta] of Object.entries(manifest.assets)) {
  images[name] = `data:image/png;base64,${readFileSync(meta.file).toString('base64')}`;
}

// ----------------------------------------------------------------- assemble

const shellHtml = readFileSync('game.html', 'utf8');
const head = shellHtml.slice(shellHtml.indexOf('<style>'), shellHtml.indexOf('</style>') + 8);
const body = shellHtml.slice(shellHtml.indexOf('<body>') + 6, shellHtml.indexOf('<script type="module">'));

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, user-scalable=no" />
<meta name="apple-mobile-web-app-capable" content="yes" />
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
<meta name="theme-color" content="#14171a" />
<link rel="icon" href="data:," />
<title>ASCENDANT — The Ascendant Works</title>
<!--
  Single-file offline build. Generated by tools/bundle.mjs — do not edit by hand;
  edit the sources and re-run \`npm run bundle\`.
-->
${head}
</head>
<body>
${body}
<script>
"use strict";
globalThis.__ASCENDANT_CONTENT = ${JSON.stringify(content)};
globalThis.__ASCENDANT_ASSETS = { manifest: ${JSON.stringify(manifest)}, images: ${JSON.stringify(images)} };
(function () {
${chunks.join('\n')}

boot().catch(function (err) {
  document.body.innerHTML =
    '<pre style="color:#e8c887;padding:24px;white-space:pre-wrap">Failed to start.\\n\\n' +
    (err && err.stack ? err.stack : err) + '</pre>';
});
})();
</script>
</body>
</html>
`;

mkdirSync('dist', { recursive: true });
writeFileSync('dist/ascendant.html', html);

const mb = statSync('dist/ascendant.html').size / 1024 / 1024;
console.log(`dist/ascendant.html  ${mb.toFixed(2)} MB`);
console.log(`  ${MODULES.length} modules, ${CONTENT.length} content files, ${Object.keys(images).length} images inlined`);
console.log(`  ${declaredIn.size} top-level names, no collisions`);
